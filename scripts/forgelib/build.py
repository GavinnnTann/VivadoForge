# Messages Vivado prints on almost every build that need no action. They stay in the summary,
# marked benign, so nobody (person or agent) burns time chasing them.
BENIGN_IDS = {
    "Synth 8-7080": "parallel synthesis is skipped for small designs",
    "Vivado 12-7122": "no previous run to reuse for incremental compile",
    "Synth 8-7079": "multithreading notice",
    "Device 21-403": "speed file loaded",
    "Constraints 18-5210": "no constraints selected for write",
}

REPORT_FILES = {
    "timing": "{top}_timing_summary_routed.rpt",
    "utilization": "{top}_utilization_placed.rpt",
    "drc": "{top}_drc_routed.rpt",
    "methodology": "{top}_methodology_drc_routed.rpt",
    "io": "{top}_io_placed.rpt",
    "power": "{top}_power_routed.rpt",
    "route_status": "{top}_route_status.rpt",
    "clock_utilization": "{top}_clock_utilization_routed.rpt",
}


def tcl_quote(value: str) -> str:
    if value == "":
        return "{}"
    if re.search(r'[{}\\]', value):
        return '"' + re.sub(r'([\\\[\]$"{}])', r"\\\1", value) + '"'
    return "{" + value + "}"


def tcl_list(items: list[str]) -> str:
    return "[list " + " ".join(tcl_quote(i) for i in items) + "]" if items else "[list]"


def write_context(cfg: Config, board: Board) -> Path:
    """Generate <build>/forge_context.tcl, the only input forge.tcl reads."""
    ensure_build_dir(cfg.build_dir)
    groups = cfg.classified_sources()
    sources = groups["verilog"] + groups["systemverilog"] + groups["vhdl"] + groups["header"] + groups["mem"] + groups["ip"]
    cons, _ = cfg.constraint_files()
    entries = {
        "name": tcl_quote(cfg.name),
        "top": tcl_quote(cfg.top),
        "board": tcl_quote(board.id),
        "part": tcl_quote(board.part),
        "build_dir": tcl_quote(cfg.build_dir.resolve().as_posix()),
        "project_dir": tcl_quote((cfg.build_dir / "vivado").resolve().as_posix()),
        "sources": tcl_list([p.resolve().as_posix() for p in sources]),
        "vhdl_sources": tcl_list([p.resolve().as_posix() for p in groups["vhdl"]]),
        "constraints": tcl_list([p.resolve().as_posix() for p in cons]),
        "include_dirs": tcl_list([p.resolve().as_posix() for p in cfg.all_include_dirs()]),
        "defines": tcl_list([f"{k}={v}" for k, v in cfg.defines.items()]),
        "generics": tcl_list([f"{k}={v}" for k, v in cfg.generics.items()]),
        "synth_strategy": tcl_quote(cfg.synth_strategy),
        "impl_strategy": tcl_quote(cfg.impl_strategy),
        "jobs": str(cfg.jobs),
        "flash_parts": tcl_list(list(board.flash.get("parts", []))),
        "flash_size_mb": str(board.flash.get("size_mb", 4)),
        "flash_interface": tcl_quote(board.flash.get("interface", "SPIx1")),
    }
    lines = ["# Generated by scripts/forge.py from forge.toml and the board definition. Do not edit.",
             "set ::forge::ctx [dict create \\"]
    lines += [f"    {k} {v} \\" for k, v in entries.items()]
    lines.append("]")
    path = cfg.build_dir / "forge_context.tcl"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def _vivado_batch(cfg: Config, vivado: Vivado, action: str, out: Out, verbose: bool) -> tuple[int, str]:
    """Run forge.tcl in Vivado batch mode with the build folder as working directory.

    Arguments are relative names without spaces: the Vivado .bat wrapper goes through cmd.exe,
    which mangles '=' and quoted paths.
    """
    shutil.copy2(FORGE_TCL, cfg.build_dir / "forge.tcl")
    (cfg.build_dir / "logs").mkdir(exist_ok=True)
    cmd = [vivado.vivado, "-mode", "batch", "-nojournal", "-log", f"logs/vivado_{action}.log",
           "-source", "forge.tcl", "-tclargs", "--forge", action, "forge_context.tcl"]
    interesting = re.compile(r"^(FORGE: |FORGE_ERROR: |ERROR|CRITICAL WARNING|\[.*\] (Launched|Finished)|INFO: \[Labtools 27-3164\])")

    def show(line: str) -> None:
        if verbose:
            out(f"    | {line}")
        elif interesting.match(line):
            out(f"    {line.removeprefix('FORGE: ').replace('FORGE_ERROR: ', 'ERROR: ')}")
    r = run(cmd, cwd=cfg.build_dir, on_line=show)
    return r.returncode, r.output


def _collect(cfg: Config, board: Board, vivado: Vivado, rc: int, output: str, seconds: float) -> dict:
    impl = cfg.build_dir / "vivado" / f"{cfg.name}.runs" / "impl_1"
    synth = impl.parent / "synth_1"
    rep_dir = cfg.build_dir / "reports"
    rep_dir.mkdir(exist_ok=True)
    copied = {}
    for key, pattern in REPORT_FILES.items():
        src = impl / pattern.format(top=cfg.top)
        if src.is_file():
            dst = rep_dir / f"{key}.rpt"
            shutil.copy2(src, dst)
            copied[key] = rel(dst)
    msgs = R.parse_messages(R.read(synth / "runme.log"), "synthesis") + \
        R.parse_messages(R.read(impl / "runme.log"), "implementation") + \
        R.parse_messages(output, "vivado")
    seen = set()
    unique = []
    for m in msgs:
        k = (m["severity"], m["id"], m["text"])
        if k not in seen:
            seen.add(k)
            unique.append(m)
    for m in unique:
        if m["id"] in BENIGN_IDS:
            m["benign"] = BENIGN_IDS[m["id"]]
    errors = [m for m in unique if m["severity"] == "error"]
    crit = [m for m in unique if m["severity"] == "critical_warning"]
    warns = [m for m in unique if m["severity"] == "warning"]
    real_warns = [m for m in warns if "benign" not in m]
    forge_err = [ln.removeprefix("FORGE_ERROR:").strip() for ln in output.splitlines() if ln.startswith("FORGE_ERROR:")]

    timing = R.parse_timing_summary(R.read(impl / REPORT_FILES["timing"].format(top=cfg.top)))
    util = R.parse_utilization(R.read(impl / REPORT_FILES["utilization"].format(top=cfg.top)))
    drc = R.parse_rule_table(R.read(impl / REPORT_FILES["drc"].format(top=cfg.top)))
    meth = R.parse_rule_table(R.read(impl / REPORT_FILES["methodology"].format(top=cfg.top)))
    bit = cfg.bitstream
    bit_ok = rc == 0 and bit.is_file()
    if bit_ok:
        shutil.copy2(bit, cfg.build_dir / f"{cfg.name}.bit")

    if not bit_ok:
        if not (synth / "runme.log").is_file():
            stage = "setup"
        elif not (impl / "runme.log").is_file():
            stage = "synthesis"
        else:
            stage = "implementation"
        status = "failed"
    elif timing.get("met") is False:
        stage, status = "timing", "timing_failed"
    else:
        stage, status = "done", "passed"

    notes = []
    if bit_ok and not timing.get("constrained", True):
        notes.append("No timing constraints: add a create_clock for the clock input (forge.py pins add <clock port>).")
    if timing.get("checks", {}).get("no_clock"):
        notes.append(f"{timing['checks']['no_clock']} register pins have no clock constraint.")
    if crit:
        notes.append(f"{len(crit)} critical warnings: read them; they usually mean the hardware will not behave as simulated.")
    if any(r["rule"] == "TIMING-18" for r in meth):
        notes.append("TIMING-18 (missing input/output delay) is expected for LEDs, buttons and other slow I/O; "
                     "add set_input_delay/set_output_delay only for synchronous interfaces to external chips.")

    return {
        "forge_version": __version__,
        "status": status,
        "stage": stage,
        "project": cfg.name,
        "top": cfg.top,
        "board": board.id,
        "part": board.part,
        "vivado": vivado.version,
        "finished": _dt.datetime.now().isoformat(timespec="seconds"),
        "seconds": round(seconds, 1),
        "bitstream": rel(bit) if bit_ok else None,
        "timing": timing,
        "utilization": util,
        "drc": [r for r in drc if r["severity"] != "Advisory"],
        "methodology": meth,
        "errors": (forge_err and [{"severity": "error", "id": "forge", "text": t} for t in forge_err] or []) + errors,
        "critical_warnings": crit,
        "warnings": warns[:100],
        "warning_count": len(real_warns),
        "benign_warning_count": len(warns) - len(real_warns),
        "summary_file": rel(cfg.summary_file),
        "reports": copied,
        "logs": {"vivado": rel(cfg.build_dir / "logs" / "vivado_build.log"),
                 "synthesis": rel(synth / "runme.log"), "implementation": rel(impl / "runme.log")},
        "notes": notes,
        "verified_on_hardware": False,
    }


def build(cfg: Config, board: Board, vivado: Vivado, out: Out, verbose: bool = False) -> dict:
    write_context(cfg, board)
    summary_path = cfg.summary_file
    if summary_path.is_file():
        summary_path.unlink()
    out(f"Building {cfg.name} (top {cfg.top}) for {board.name} [{board.part}] with Vivado {vivado.version}")
    out(f"  build folder: {cfg.build_dir.as_posix()}")
    t0 = time.monotonic()
    rc, output = _vivado_batch(cfg, vivado, "build", out, verbose)
    summary = _collect(cfg, board, vivado, rc, output, time.monotonic() - t0)
    summary_path.parent.mkdir(parents=True, exist_ok=True)
    summary_path.write_text(json.dumps(summary, indent=2), encoding="utf-8")
    return summary


def format_summary(s: dict) -> list[str]:
    lines = []
    status = {"passed": "BUILD PASSED", "timing_failed": "BUILD FINISHED, TIMING FAILED",
              "failed": f"BUILD FAILED during {s.get('stage')}"}.get(s["status"], s["status"])
    lines.append(f"{status}  ({s.get('seconds', 0)} s, Vivado {s.get('vivado')})")
    for e in s.get("errors", [])[:15]:
        where = f"  --> {e['file']}:{e['line']}" if e.get("file") else ""
        lines.append(f"  ERROR    [{e['id']}] {e['text']}{where}")
    for c in s.get("critical_warnings", [])[:15]:
        where = f"  --> {c['file']}:{c['line']}" if c.get("file") else ""
        lines.append(f"  CRITICAL [{c['id']}] {c['text']}{where}")
    t = s.get("timing") or {}
    if "wns" in t:
        met = {True: "met", False: "NOT MET", None: "unconstrained"}[t.get("met")]
        lines.append(f"  timing:  {met}   WNS {t.get('wns')} ns   TNS {t.get('tns')} ns   "
                     f"WHS {t.get('whs')} ns   failing endpoints {t.get('tns_failing')}")
    u = s.get("utilization") or {}
    if u:
        parts = [f"{k.upper()} {v['used']}/{v['available']} ({v['percent']}%)" for k, v in u.items()
                 if k in ("lut", "ff", "bram", "dsp", "io")]
        lines.append("  usage:   " + "   ".join(parts))
    if s.get("warning_count"):
        lines.append(f"  warnings: {s['warning_count']} to review (all messages: {s.get('summary_file', 'reports/summary.json')})")
    elif s.get("benign_warning_count"):
        lines.append(f"  warnings: none that need action ({s['benign_warning_count']} routine Vivado notices)")
    for n in s.get("notes", []):
        lines.append(f"  note:    {n}")
    if s.get("bitstream"):
        lines.append(f"  bitstream: {s['bitstream']}")
        lines.append("  A bitstream is not proof that the hardware works: test it on the board.")
    return lines


def hardware(cfg: Config, board: Board, vivado: Vivado, action: str, out: Out, verbose: bool = False) -> dict:
    """program | flash | devices."""
    write_context(cfg, board)
    t0 = time.monotonic()
    rc, output = _vivado_batch(cfg, vivado, action, out, verbose)
    errors = [ln.removeprefix("FORGE_ERROR:").strip() for ln in output.splitlines() if ln.startswith("FORGE_ERROR:")]
    errors += [m["text"] for m in R.parse_messages(output) if m["severity"] == "error"]
    result: dict = {"action": action, "ok": rc == 0 and not errors, "seconds": round(time.monotonic() - t0, 1),
                    "errors": errors, "log": rel(cfg.build_dir / "logs" / f"vivado_{action}.log")}
    if action == "devices":
        devs = []
        for ln in output.splitlines():
            if ln.startswith("FORGE_DEVICE:"):
                body = ln.removeprefix("FORGE_DEVICE:").strip()
                if body == "none":
                    continue
                devs.append(dict(kv.split("=", 1) for kv in body.split() if "=" in kv))
        result["devices"] = devs
    return result


def last_summary(cfg: Config) -> dict | None:
    if cfg.summary_file.is_file():
        try:
            return json.loads(cfg.summary_file.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            return None
    return None
